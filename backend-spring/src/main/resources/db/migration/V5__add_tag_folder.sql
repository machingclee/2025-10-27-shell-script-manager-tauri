-- Grouping folder for tags. tag.tag_folder_id is optional.

CREATE TABLE tag_folder (
    id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

ALTER TABLE tag
    ADD COLUMN IF NOT EXISTS tag_folder_id INT;

ALTER TABLE tag
    ADD CONSTRAINT tag_tag_folder_id_fkey
    FOREIGN KEY (tag_folder_id) REFERENCES tag_folder (id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS tag_tag_folder_id_idx ON tag (tag_folder_id);
