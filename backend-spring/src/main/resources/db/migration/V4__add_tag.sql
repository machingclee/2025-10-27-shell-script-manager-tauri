-- Tag catalog, an assignment row (expand later), and the script link.
-- H2 cannot index LOWER(name). name_lower is generated so uniqueness stays case-insensitive.
-- Drop first so a failed earlier attempt, which left "tag" behind, can be retried.

DROP TABLE IF EXISTS rel_shellscript_tag;
DROP TABLE IF EXISTS assigned_tag;
DROP TABLE IF EXISTS tag;

CREATE TABLE tag (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    name_lower VARCHAR(255) GENERATED ALWAYS AS (LOWER(name)) UNIQUE
);

CREATE TABLE assigned_tag (
    id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tag_id INT NOT NULL
);
CREATE INDEX assigned_tag_tag_id_idx ON assigned_tag (tag_id);

CREATE TABLE rel_shellscript_tag (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shell_script_id INT NOT NULL,
    assigned_tag_id INT NOT NULL
);
CREATE UNIQUE INDEX rel_shellscript_tag_shell_script_id_assigned_tag_id_key
    ON rel_shellscript_tag (shell_script_id, assigned_tag_id);
CREATE INDEX rel_shellscript_tag_shell_script_id_idx ON rel_shellscript_tag (shell_script_id);
CREATE INDEX rel_shellscript_tag_assigned_tag_id_idx ON rel_shellscript_tag (assigned_tag_id);

ALTER TABLE assigned_tag
    ADD CONSTRAINT assigned_tag_tag_id_fkey
    FOREIGN KEY (tag_id) REFERENCES tag (id) ON DELETE CASCADE;

ALTER TABLE rel_shellscript_tag
    ADD CONSTRAINT rel_shellscript_tag_shell_script_id_fkey
    FOREIGN KEY (shell_script_id) REFERENCES shell_script (id) ON DELETE CASCADE;
ALTER TABLE rel_shellscript_tag
    ADD CONSTRAINT rel_shellscript_tag_assigned_tag_id_fkey
    FOREIGN KEY (assigned_tag_id) REFERENCES assigned_tag (id) ON DELETE CASCADE;
